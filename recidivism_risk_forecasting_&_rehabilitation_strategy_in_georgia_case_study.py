import pandas as pd
import numpy as np
from google.colab import files
df = pd.read_csv('/NIJ_s_Recidivism_Challenge_Full_Dataset.csv')

# Looking at the first 10 rows of the dataset
print(df.head(10))
#Checking for null vlaues
print(df.isna().any())

"""Average Recidivism Rate (within 3 years) Based on Program Attendance"""

prog_df = (df.groupby('Program_Attendances')['Recidivism_Within_3years'].mean() * 100).round(1).reset_index(name='recidivism_rate')
print(prog_df)

"""Impact of Employment on Avg Recidivism Rate"""

#Checking if nulls for 'Percent_Days_Employed' correlate with employment exemption
print(pd.crosstab(df['Employment_Exempt'], df['Percent_Days_Employed'].isnull()))

cleaned_df = df.dropna(subset=['Percent_Days_Employed']).copy()

# Defining the bins and labels.
# Since Percent_Days_Employed goes from 0.0 to 1.0 (representing 0% to 100%):
bins = [-0.01, 0.0, 0.25, 0.50, 0.75, 1.0]
labels = ['0%', '1–25%', '26–50%', '51–75%', '76–100%']

# Create the binned column
cleaned_df['Employment_Group'] = pd.cut(cleaned_df['Percent_Days_Employed'], bins=bins, labels=labels)

# Group by the new bins and calculate the average recidivism rate
emp_df = (cleaned_df.groupby('Employment_Group', observed=False)['Recidivism_Within_3years'].mean() * 100).round(1).reset_index(name='recidivism_rate')
print(emp_df)

"""Impact of Substance Use on Avg Recidivism Rate"""

# Boolean evaluates to true if at least one test result is > 0
df['Postive_Substance_Test'] = (df['DrugTests_THC_Positive'] > 0) | (df['DrugTests_Cocaine_Positive'] > 0) | (df['DrugTests_Meth_Positive'] > 0) | (df['DrugTests_Other_Positive'] > 0)
# Boolean evaluates to true if the selected result is null (if tests are missing it should be for all substances)
df['Missing_Subtance_Tests'] = df['DrugTests_THC_Positive'].isna()

# Defining logical conditions
conditions = [
    df['Missing_Subtance_Tests'],     # Condition 1: Missing / Un-tested
    df['Postive_Substance_Test'],     # Condition 2: Tested & At least one positive
]

# Defining the corresponding labels
choices = [
    'Missing / Un-tested',
    'Tested - Positive',
]

# 'default' handles everyone who didn't trigger either above
# (i.e., not missing AND not positive -> Tested - All Clean)
df['Drug_Test_Status'] = np.select(conditions, choices, default='Tested - Clean')

drug_summary = df.groupby('Drug_Test_Status')['Recidivism_Within_3years'].agg(
    recidivism_rate='mean',
    headcount='count'
).reset_index()

# Format the rate as a clean percentage for presentation
drug_summary['recidivism_rate'] = (drug_summary['recidivism_rate'] * 100).round(1)

print(drug_summary)

"""Impact of Facility Type on Recidivism Rates"""

cy_df = pd.read_csv('Calendar Year (CY) Reconviction Rates (2011–2022 Releases) - Recidivism case study.csv')

# Defining the key facility categories to evaluate
target_facilities = [
    'Transition centers',
    'County CI',
    'All inmate facilities **',
    'State prison, IBCs',
    'Private prisons'
]

# Filtering the dataframe to just those facility types
facility_comparison = cy_df[cy_df['Facility Type'].isin(target_facilities)].copy()

# Identifying the year columns (e.g., '2011' through '2022')
year_cols = [col for col in cy_df.columns if col.isdigit()]

# Ensuring year columns are numeric (converting any potential strings/whitespace)
facility_comparison[year_cols] = facility_comparison[year_cols].apply(pd.to_numeric, errors='coerce')

# Calculating multi-year metrics: Historical Mean, Min, and Max
facility_comparison['Multi_Year_Mean'] = facility_comparison[year_cols].mean(axis=1).round(1)
facility_comparison['10_Year_Min'] = facility_comparison[year_cols].min(axis=1).round(1)
facility_comparison['10_Year_Max'] = facility_comparison[year_cols].max(axis=1).round(1)

# 6. Display a clean summary of latest year vs. historical average
summary_table = facility_comparison[[
    'Facility Type',
    '2022',
    'Multi_Year_Mean',
    '10_Year_Min',
    '10_Year_Max'
]].sort_values(by='2022')

print(summary_table.to_string(index=False))

"""Export Summaries to Multi-tab Excel Workbook"""

excel_filename = 'Recidivism_Case_Study_Summary.xlsx'

# Write your clean DataFrames straight to their respective sheet tabs
with pd.ExcelWriter(excel_filename) as writer:
    prog_df.to_excel(writer, sheet_name='Program_Attendance', index=False)
    emp_df.to_excel(writer, sheet_name='Employment_Tiers', index=False)
    drug_summary.to_excel(writer, sheet_name='Substance_Use', index=False)
    summary_table.to_excel(writer, sheet_name='Facility_Comparison', index=False)

print(f"Excel workbook '{excel_filename}' successfully compiled and downloaded!")

# Automatically trigger the local download in your browser
files.download(excel_filename)